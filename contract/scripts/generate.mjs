// Generates TypeScript types from the contract (CLAUDE.md "Stack": openapi-typescript).
//   contract/openapi.yaml       -> contract/generated/openapi.ts
//   contract/events/*.json      -> contract/generated/events.ts
// With --check, fails if the committed files are out of date (used in CI).
import { readFile, writeFile, readdir, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import { compile } from "json-schema-to-typescript";
import { format } from "prettier";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outDir = path.join(root, "generated");
const eventsDir = path.join(root, "events");
const check = process.argv.includes("--check");

const banner = (src) =>
  `/* eslint-disable */\n// GENERATED by contract/scripts/generate.mjs from ${src}. Do not edit; run \`npm run gen\`.\n\n`;

async function openapiTypes() {
  const ast = await openapiTS(new URL("../openapi.yaml", import.meta.url), {
    alphabetize: false,
    exportType: true,
  });
  return banner("contract/openapi.yaml") + astToString(ast);
}

async function eventTypes() {
  const files = (await readdir(eventsDir)).filter(
    (f) => f.endsWith(".json") && !["catalog.json", "phoenix-message.json", "common.json"].includes(f),
  );
  files.sort();
  // One wrapper schema that references every event file, so shared definitions in
  // common.json are emitted once instead of once per file.
  const wrapper = {
    title: "ContractEvents",
    description: "All WebSocket event payloads (see contract/events/catalog.json).",
    type: "object",
    additionalProperties: false,
    properties: Object.fromEntries(files.map((f) => [f.replace(/\.json$/, ""), { $ref: `./${f}` }])),
  };
  const ts = await compile(wrapper, "ContractEvents", {
    cwd: eventsDir,
    bannerComment: "",
    additionalProperties: false,
    unreachableDefinitions: false,
    ignoreMinAndMaxItems: true,
    style: { singleQuote: false },
  });
  const frame =
    "\n/** Phoenix Channels V2 frame: [join_ref, ref, topic, event, payload] (events/phoenix-message.json). */\n" +
    "export type PhoenixMessage<P = Record<string, unknown>> = [\n" +
    "  joinRef: string | null,\n  ref: string | null,\n  topic: string,\n  event: string,\n  payload: P,\n];\n";
  return banner("contract/events/*.json") + ts + frame;
}

const outputs = {
  "openapi.ts": await openapiTypes(),
  "events.ts": await eventTypes(),
};

await mkdir(outDir, { recursive: true });
let stale = [];
for (const [name, raw] of Object.entries(outputs)) {
  const file = path.join(outDir, name);
  const content = await format(raw, { parser: "typescript", printWidth: 100 });
  if (check) {
    const current = await readFile(file, "utf8").catch(() => "");
    if (current !== content) stale.push(`contract/generated/${name}`);
  } else {
    await writeFile(file, content);
    console.log(`wrote contract/generated/${name}`);
  }
}
if (stale.length) {
  console.error(`Generated types are out of date: ${stale.join(", ")}\nRun \`npm run gen\` and commit the result.`);
  process.exit(1);
}
if (check) console.log("generated types are up to date");
