-- Backend step 13. Idempotent: the mock runs these files on start too.
--
-- Messages the platform sends itself on a customer's trunk (Sms.Switch.Commands.Inject: Test SMS from the Route
-- Simulator, EDR Repush) are marked on both their attempt and outcome rows: internal_kind 'test' or 'repush', '' for
-- the customer's own traffic. The customer portal leaves them out (a customer never sees our tests, and a repushed
-- message is not shown twice); the staff screens keep them.
ALTER TABLE edr ADD COLUMN IF NOT EXISTS internal_kind LowCardinality(String) DEFAULT '' AFTER repush_request_id;
ALTER TABLE edr_receipt ADD COLUMN IF NOT EXISTS internal_kind LowCardinality(String) DEFAULT '' AFTER msg_count;

CREATE OR REPLACE VIEW edr_all AS
SELECT
    'attempt'            AS kind,
    edr_id,
    start_time,
    submit_time,
    msg_type,
    business_company_id,
    product_category_id,
    c_enterprise_id,
    c_trunk_id,
    c_am_user_id,
    c_ip,
    v_enterprise_id,
    v_trunk_id,
    v_am_user_id,
    v_ip,
    c_mccmnc,
    c_mcc,
    c_country_iso,
    v_mccmnc,
    src_addr,
    v_src_addr,
    route_rule_id,
    route_type,
    c_rate_table_id,
    v_rate_table_id,
    c_rate,
    v_rate,
    c_currency,
    c_ex_rate,
    v_currency,
    v_ex_rate,
    attempt_no,
    is_final_attempt,
    is_submit_success,
    command_status,
    dlr_reroute,
    msg_count,
    msg_status,
    if(c_msg_status = 'ACCEPTD', '', c_msg_status) AS c_msg_status,
    delivery_delay_ms,
    is_customer_billable,
    is_vendor_billable,
    revenue,
    cost,
    revenue_sys,
    cost_sys,
    hlr_provider_id,
    hlr_fetch_type,
    hlr_is_ported,
    hlr_is_accomplished,
    hlr_cost_sys,
    internal_kind
FROM edr
UNION ALL
SELECT
    'outcome'            AS kind,
    edr_id,
    start_time,
    start_time           AS submit_time,
    CAST('MT', 'Enum8(\'MT\' = 1, \'MO\' = 2)') AS msg_type,
    business_company_id,
    product_category_id,
    c_enterprise_id,
    c_trunk_id,
    c_am_user_id,
    c_ip,
    v_enterprise_id,
    v_trunk_id,
    v_am_user_id,
    v_ip,
    c_mccmnc,
    substring(c_mccmnc, 1, 3) AS c_mcc,
    c_country_iso,
    v_mccmnc,
    src_addr,
    v_src_addr,
    route_rule_id,
    route_type,
    c_rate_table_id,
    v_rate_table_id,
    c_rate,
    v_rate,
    c_currency,
    c_ex_rate,
    v_currency,
    v_ex_rate,
    attempt_no,
    toUInt8(0)           AS is_final_attempt,
    toUInt8(0)           AS is_submit_success,
    toInt16(0)           AS command_status,
    toUInt8(0)           AS dlr_reroute,
    msg_count,
    msg_status,
    c_msg_status,
    delivery_delay_ms,
    is_customer_billable,
    is_vendor_billable,
    revenue,
    cost,
    revenue_sys,
    cost_sys,
    hlr_provider_id,
    'none'               AS hlr_fetch_type,
    toUInt8(0)           AS hlr_is_ported,
    toUInt8(0)           AS hlr_is_accomplished,
    toDecimal64(0, 6)    AS hlr_cost_sys,
    internal_kind
FROM edr_receipt
WHERE kind = 'outcome';
