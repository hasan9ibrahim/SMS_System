-- E-mail templates as full designs (§11, team trial round 1): uploaded images, the e-mail as sent, test sends.

-- Images used in templates. Sent e-mails embed them inline (cid), so recipients see them without
-- allowing remote images; the system shows them from /email-assets/{id}/file.
CREATE TABLE IF NOT EXISTS email_assets (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_company_id  bigint REFERENCES business_companies(id),
  name                 text NOT NULL,
  content_type         text NOT NULL CHECK (content_type IN ('image/png', 'image/jpeg', 'image/gif')),
  size                 integer NOT NULL,
  width                integer NOT NULL,
  height               integer NOT NULL,
  data                 bytea NOT NULL,
  uploaded_by_id       bigint REFERENCES users(id),
  uploaded_at          timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz
);
CREATE INDEX IF NOT EXISTS email_assets_company_idx ON email_assets (business_company_id, uploaded_at DESC);

