SET search_path = sms, public;

-- ---------------------------------------------------------------- invoices
-- Balance sign (§7, decided 2026-10-17): invoice opening and closing balances follow the same
-- rule as every balance (positive = the client's credit, negative = owed). They were stored as
-- owed amounts; flip them once. Closing = opening − usage; due = the owed part of the closing.
UPDATE invoices SET opening_balance = -opening_balance,
                    closing_balance = -opening_balance - usage_charges;
UPDATE invoices SET due_amount = GREATEST(0, -closing_balance);

ALTER TABLE invoices
  -- Generate Request Invoice Type (§12.3): proforma invoices ask for money in advance and do not
  -- count as usage in balances.
  ADD COLUMN kind text NOT NULL DEFAULT 'traffic' CHECK (kind IN ('traffic','proforma')),
  -- Usage days are cut at midnight in this zone (§13.31).
  ADD COLUMN timezone text NOT NULL DEFAULT 'UTC',
  ADD COLUMN email_sent_at timestamptz,
  ADD COLUMN email_recipients text[] NOT NULL DEFAULT '{}',
  ADD COLUMN updated_by_id bigint REFERENCES users(id);
UPDATE invoices i SET timezone = e.billing_timezone,
                      email_sent_at = CASE WHEN i.email_status = 'sent' THEN i.inserted_at + interval '5 minutes' END
  FROM enterprises e WHERE e.id = i.enterprise_id;
CREATE INDEX invoices_number_trgm ON invoices USING gin (invoice_number gin_trgm_ops);

-- Invoice Request list (§12.3 /invoices/manual): one row per enterprise per Generate Request,
-- Regenerate or Auto Invoicing run; runs in the background (pending → inprogress → done).
CREATE TABLE invoice_requests (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind            text NOT NULL CHECK (kind IN ('traffic','proforma')),
  invoice_type    text NOT NULL CHECK (invoice_type IN ('auto','manual')),
  regenerate      boolean NOT NULL DEFAULT false,
  enterprise_id   bigint NOT NULL REFERENCES enterprises(id),
  timezone        text NOT NULL,
  usage_start     date NOT NULL,
  usage_end       date NOT NULL,
  due_date_type   text NOT NULL CHECK (due_date_type IN ('auto','manual')),
  due_date        date,
  invoice_number  text,
  amount          numeric(14,2),
  volume          bigint,
  currency        char(3) REFERENCES currencies(iso),
  invoice_date    date,
  remarks         text,
  status          text NOT NULL CHECK (status IN ('pending','inprogress','completed','failed')),
  error           text,
  invoice_id      bigint REFERENCES invoices(id),
  started_at      timestamptz,
  finished_at     timestamptz,
  created_by_id   bigint REFERENCES users(id),               -- null = Auto Invoicing
  inserted_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX invoice_requests_time_idx ON invoice_requests(inserted_at DESC);
CREATE INDEX invoice_requests_invoice_idx ON invoice_requests(invoice_id);

-- Requests behind the existing invoices (auto runs start at about 00:01, §12.3).
INSERT INTO invoice_requests (kind, invoice_type, enterprise_id, timezone, usage_start, usage_end,
                              due_date_type, invoice_date, status, error, invoice_id, started_at,
                              finished_at, created_by_id, inserted_at)
SELECT i.kind, i.invoice_type, i.enterprise_id, i.timezone, i.usage_start, i.usage_end, 'auto',
       i.invoice_date, CASE i.status WHEN 'failed' THEN 'failed' WHEN 'completed' THEN 'completed' ELSE i.status END,
       CASE WHEN i.status = 'failed' THEN 'Invoice format file could not be read' END, i.id,
       i.inserted_at + interval '1 minute', CASE WHEN i.status IN ('completed','failed') THEN i.inserted_at + interval '2 minutes' END,
       CASE WHEN i.invoice_type = 'manual' THEN i.created_by_id END, i.inserted_at + interval '1 minute'
  FROM invoices i ORDER BY i.inserted_at, i.id;

-- ---------------------------------------------------------------- reconciliation rules (§13.31)
CREATE TABLE recon_rules (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id    bigint REFERENCES enterprises(id),         -- null = the default rule
  amount_pct       numeric(6,3),
  amount_fixed     numeric(14,2),
  amount_combine   text NOT NULL DEFAULT 'stricter' CHECK (amount_combine IN ('stricter','looser')),
  count_pct        numeric(6,3),
  count_fixed      bigint,
  count_combine    text NOT NULL DEFAULT 'looser' CHECK (count_combine IN ('stricter','looser')),
  destination_pct  numeric(6,3),
  auto_send        text NOT NULL DEFAULT 'auto' CHECK (auto_send IN ('auto','confirm')),
  disputed_in_soa  text NOT NULL DEFAULT 'separate_block' CHECK (disputed_in_soa IN ('exclude','separate_block')),
  updated_by_id    bigint REFERENCES users(id),
  inserted_at      timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  deleted_at       timestamptz
);
CREATE UNIQUE INDEX recon_rules_default_uq ON recon_rules ((1)) WHERE enterprise_id IS NULL AND deleted_at IS NULL;
CREATE UNIQUE INDEX recon_rules_enterprise_uq ON recon_rules (enterprise_id) WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------- vendor invoices (§13.31)
-- Status after the comparison: a match is accepted, a mismatch is disputed until billing rejects,
-- keeps it pending (disputed, with a note) or accepts it later.
ALTER TABLE vendor_invoices DROP CONSTRAINT vendor_invoices_recon_status_check;
ALTER TABLE vendor_invoices
  ADD COLUMN comparison text CHECK (comparison IN ('match','mismatch','no_data')),
  ADD COLUMN email_status text NOT NULL DEFAULT 'none' CHECK (email_status IN ('none','waiting','sent','failed')),
  ADD COLUMN email_sent_at timestamptz,
  ADD COLUMN source text NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','import','email')),
  ADD COLUMN checked_at timestamptz,
  ADD COLUMN check_reasons text[] NOT NULL DEFAULT '{}',
  ADD COLUMN rule_snapshot jsonb,
  ADD COLUMN updated_by_id bigint REFERENCES users(id),
  ALTER COLUMN charge_volume DROP NOT NULL,
  ALTER COLUMN our_volume DROP NOT NULL,
  ALTER COLUMN our_amount DROP NOT NULL;
UPDATE vendor_invoices SET
  comparison = CASE WHEN abs(charge_amount - our_amount) <= our_amount * 0.01 THEN 'match' ELSE 'mismatch' END,
  email_status = CASE recon_status WHEN 'match' THEN 'waiting' WHEN 'accepted' THEN 'sent' WHEN 'rejected' THEN 'sent' ELSE 'none' END,
  email_sent_at = CASE WHEN recon_status IN ('accepted','rejected') THEN updated_at + interval '10 minutes' END,
  source = CASE WHEN id % 4 = 0 THEN 'manual' ELSE 'email' END,
  checked_at = inserted_at + interval '3 minutes',
  recon_status = CASE recon_status WHEN 'match' THEN 'accepted' WHEN 'mismatch' THEN 'disputed'
                                   WHEN 'pending' THEN 'disputed' ELSE recon_status END;
UPDATE vendor_invoices SET check_reasons = ARRAY[
  'Amount ' || CASE comparison WHEN 'match' THEN 'within' ELSE 'outside' END || ' tolerance: '
  || to_char(charge_amount - our_amount, 'FM999999990.00') || ' ' || currency]
 WHERE check_reasons = '{}';
ALTER TABLE vendor_invoices ADD CONSTRAINT vendor_invoices_recon_status_check
  CHECK (recon_status IN ('pending','accepted','disputed','rejected'));
CREATE INDEX vendor_invoices_date_idx ON vendor_invoices(invoice_date DESC);
CREATE INDEX vendor_invoices_number_trgm ON vendor_invoices USING gin (invoice_number gin_trgm_ops);

-- Per-destination lines read from the invoice, when it has them.
CREATE TABLE vendor_invoice_lines (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_invoice_id  bigint NOT NULL REFERENCES vendor_invoices(id) ON DELETE CASCADE,
  mccmnc             text NOT NULL,
  volume             bigint,
  amount             numeric(14,4) NOT NULL,
  UNIQUE (vendor_invoice_id, mccmnc)
);

-- Every status change, note and e-mail with user and time (§13.31).
CREATE TABLE vendor_invoice_events (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_invoice_id  bigint NOT NULL REFERENCES vendor_invoices(id) ON DELETE CASCADE,
  kind               text NOT NULL CHECK (kind IN ('created','edited','checked','status','note','email')),
  status_from        text,
  status_to          text,
  note               text,
  email_to           text[] NOT NULL DEFAULT '{}',
  user_id            bigint REFERENCES users(id),             -- null = the platform
  inserted_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX vendor_invoice_events_invoice_idx ON vendor_invoice_events(vendor_invoice_id, inserted_at);

INSERT INTO vendor_invoice_events (vendor_invoice_id, kind, note, user_id, inserted_at)
SELECT id, 'created', CASE source WHEN 'email' THEN 'Received at the billing mailbox' ELSE 'Added by hand' END,
       CASE WHEN source = 'manual' THEN created_by_id END, inserted_at FROM vendor_invoices;
INSERT INTO vendor_invoice_events (vendor_invoice_id, kind, status_from, status_to, note, user_id, inserted_at)
SELECT id, 'checked', NULL, CASE comparison WHEN 'match' THEN 'accepted' ELSE 'disputed' END, check_reasons[1], NULL, checked_at
  FROM vendor_invoices;
INSERT INTO vendor_invoice_events (vendor_invoice_id, kind, status_from, status_to, note, user_id, inserted_at)
SELECT id, 'status', 'disputed', recon_status,
       CASE recon_status WHEN 'accepted' THEN 'Agreed after discussion' ELSE 'Difference above tolerance, our EDR summary attached' END,
       created_by_id, updated_at + interval '2 days'
  FROM vendor_invoices WHERE comparison = 'mismatch' AND recon_status IN ('accepted','rejected');
INSERT INTO vendor_invoice_events (vendor_invoice_id, kind, note, email_to, user_id, inserted_at)
SELECT v.id, 'email', CASE v.recon_status WHEN 'rejected' THEN 'Rejection sent' ELSE 'Acceptance sent' END,
       COALESCE((SELECT c.emails FROM enterprise_contacts c WHERE c.enterprise_id = v.enterprise_id
                  AND c.contact_type IN ('finance','commercial') ORDER BY c.contact_type = 'finance' DESC LIMIT 1), '{}'),
       NULL, v.email_sent_at
  FROM vendor_invoices v WHERE v.email_status = 'sent';

