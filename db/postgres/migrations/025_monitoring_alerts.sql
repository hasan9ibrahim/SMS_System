-- Monitoring alerts (spec §13.6, §13.7), build step 5.12: alert rules evaluated on the server,
-- incidents with notes, the Monitoring Alert e-mail type, and per-user alert sound settings.
SET search_path = sms, public;

CREATE TABLE alert_rules (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                   text NOT NULL,
  status                 text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  description            text,
  scope_kind             text NOT NULL CHECK (scope_kind IN ('all','customer','customer_trunk','vendor','vendor_trunk',
                           'country','mccmnc','sender_id','product_category')),
  scope_ids              bigint[] NOT NULL DEFAULT '{}',
  scope_values           text[] NOT NULL DEFAULT '{}',
  metric                 text NOT NULL CHECK (metric IN ('attempts','submitted','delivered','tps','asr','dlr','margin',
                           'margin_pct','revenue','avg_delivery_delay','bind_status')),
  condition_type         text NOT NULL CHECK (condition_type IN ('above','below','increase_pct','decrease_pct','started',
                           'stopped','bind_down')),
  condition_value        numeric,
  condition_baseline     text CHECK (condition_baseline IN ('previous_window','yesterday','last_week')),
  window_minutes         smallint NOT NULL DEFAULT 15 CHECK (window_minutes IN (1,5,15,30,60)),
  min_sample             integer NOT NULL DEFAULT 0,
  active_always          boolean NOT NULL DEFAULT true,
  active_days            smallint[] NOT NULL DEFAULT '{0,1,2,3,4,5,6}',
  active_from_hour       smallint NOT NULL DEFAULT 0,
  active_to_hour         smallint NOT NULL DEFAULT 24,
  severity               text NOT NULL CHECK (severity IN ('info','warning','critical')),
  notify_user_ids        bigint[] NOT NULL DEFAULT '{}',
  notify_department_ids  bigint[] NOT NULL DEFAULT '{}',
  channel_popup          boolean NOT NULL DEFAULT true,
  channel_sound          boolean NOT NULL DEFAULT true,
  channel_email          boolean NOT NULL DEFAULT false,
  email_addresses        text[] NOT NULL DEFAULT '{}',
  partner_contact_type   text CHECK (partner_contact_type IN ('commercial','technical','rates','finance')),
  repeat_minutes         integer,
  cooldown_minutes       integer NOT NULL DEFAULT 15,
  recovery_notice        boolean NOT NULL DEFAULT true,
  last_triggered_at      timestamptz,
  updated_by_id          bigint REFERENCES users(id),
  inserted_at            timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  deleted_at             timestamptz
);
CREATE UNIQUE INDEX alert_rules_name_uq ON alert_rules (lower(name)) WHERE deleted_at IS NULL;

CREATE TABLE incidents (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_id          bigint NOT NULL REFERENCES alert_rules(id),
  severity         text NOT NULL CHECK (severity IN ('info','warning','critical')),
  metric           text NOT NULL,
  entity_kind      text NOT NULL,
  entity_id        bigint,
  entity_name      text NOT NULL,
  message          text NOT NULL,
  state            text NOT NULL DEFAULT 'open' CHECK (state IN ('open','acknowledged','recovered')),
  current_value    numeric,
  baseline_value   numeric,
  peak_value       numeric,
  started_at       timestamptz NOT NULL,
  ended_at         timestamptz,
  acknowledged_by_id bigint REFERENCES users(id),
  acknowledged_at  timestamptz,
  snoozed_until    timestamptz,
  last_notified_at timestamptz,
  emailed_at       timestamptz,
  digest_pending   boolean NOT NULL DEFAULT false
);
CREATE INDEX incidents_started_idx ON incidents (started_at DESC);
CREATE INDEX incidents_open_idx ON incidents (rule_id, entity_kind, entity_id) WHERE state <> 'recovered';

CREATE TABLE incident_notes (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id  bigint NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
  user_id      bigint REFERENCES users(id),
  text         text NOT NULL,
  inserted_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX incident_notes_incident_idx ON incident_notes (incident_id);

-- Per-user alert sounds (§13.6): mute and a sound per severity.
ALTER TABLE users ADD COLUMN alert_sounds jsonb;

-- Monitoring Alert e-mails (§13.7).
ALTER TABLE email_logs DROP CONSTRAINT email_logs_email_type_check;
ALTER TABLE email_logs ADD CONSTRAINT email_logs_email_type_check CHECK (email_type IN ('send_rate','send_tech_info',
  'invoice','check_smtp','bind_down_alert','otp','forgot_password','auto_upload_rate','credit_alert','balance_alert',
  'schedule_report_alert','traffic_alert','auto_upload_rejected','daily_report','broadcast','trouble_ticket','send_soa',
  'payment_confirmation','invoice_acceptance','invoice_rejection','monitoring_alert'));
ALTER TABLE email_templates DROP CONSTRAINT email_templates_email_type_check;
ALTER TABLE email_templates ADD CONSTRAINT email_templates_email_type_check CHECK (email_type IN ('customer_rate',
  'invoice','low_balance','bind_down','customer_tech_info','trunk_change_info','soa_statement','rate_upload_notification',
  'traffic_alert','auto_upload_rejected','trouble_ticket','send_soa','monitoring_alert'));

