-- Cleanup Center (spec §13.19, §13.20), build step 5.19: findings of the nightly scan (unassigned,
-- unused, expired, identical, near-duplicate, shadowed, conflicting and broken rules; unattached or
-- identical rate tables and duplicate lines; idle trunks; dormant or duplicate enterprises; unused
-- lists; idle users), reviewed before anything changes, and the scan's settings.
SET search_path = sms, public;

CREATE TABLE cleanup_findings (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint    text NOT NULL UNIQUE,              -- kind + the records, so a rescan updates the same finding
  area           text NOT NULL CHECK (area IN ('rules','rates','trunks','enterprises','lists','users')),
  kind           text NOT NULL,
  entity_type    text NOT NULL,
  entity_ids     bigint[] NOT NULL,
  title          text NOT NULL,
  why            text NOT NULL,
  suggestion     text NOT NULL CHECK (suggestion IN ('merge','archive','deactivate','reassign','reorder','review')),
  actions        text[] NOT NULL,
  impact         text NOT NULL,
  messages_30d   bigint,
  state          text NOT NULL DEFAULT 'open' CHECK (state IN ('open','awaiting_approval','applied','ignored','resolved')),
  ignore_reason  text,
  requested_action text,
  requested_by_id bigint REFERENCES users(id),
  detected_at    timestamptz NOT NULL DEFAULT now(),
  last_seen_at   timestamptz NOT NULL DEFAULT now(),
  applied_at     timestamptz,
  applied_by_id  bigint REFERENCES users(id),
  change_id      bigint REFERENCES changes(id)
);
CREATE INDEX cleanup_findings_state_idx ON cleanup_findings (state, area);

CREATE TABLE cleanup_settings (
  id                int PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  unused_days       int NOT NULL DEFAULT 30,
  dormant_days      int NOT NULL DEFAULT 90,
  user_idle_days    int NOT NULL DEFAULT 90,
  expired_days      int NOT NULL DEFAULT 7,
  require_approval  boolean NOT NULL DEFAULT false,
  summary_emails    text[] NOT NULL DEFAULT '{}',
  last_scan_at      timestamptz,
  last_summary_at   timestamptz
);
