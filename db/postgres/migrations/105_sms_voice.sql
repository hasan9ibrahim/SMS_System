-- SMS to voice in the switch (§8, decided 2026-10-31): a matching message is always a call over SIP to the operator's
-- own voice switch, placed by the local Asterisk, saying "Your verification code is <digits>" in English. These are the
-- voice switches calls go to (docs/SMS_TO_VOICE.md). Add only (rolling deploys): safe to run twice.
CREATE TABLE IF NOT EXISTS voice_gateways (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL,
  host            text NOT NULL,
  port            integer NOT NULL DEFAULT 5060 CHECK (port BETWEEN 1 AND 65535),
  transport       text NOT NULL DEFAULT 'udp' CHECK (transport IN ('udp', 'tcp', 'tls')),
  username        text,
  password_enc    text,
  from_domain     text,
  -- The number the called party sees: the message's sender when it is a number (else fixed_caller_id), or always fixed.
  caller_id_mode  text NOT NULL DEFAULT 'sender' CHECK (caller_id_mode IN ('sender', 'fixed')),
  fixed_caller_id text,
  -- Put before the receiver number when dialling (the voice switch's routing prefix, often empty).
  dial_prefix     text NOT NULL DEFAULT '',
  codecs          text[] NOT NULL DEFAULT '{alaw,ulaw}',
  max_calls       integer NOT NULL DEFAULT 10 CHECK (max_calls BETWEEN 1 AND 1000),
  ring_timeout_s  integer NOT NULL DEFAULT 30 CHECK (ring_timeout_s BETWEEN 5 AND 120),
  retry_delay_s   integer NOT NULL DEFAULT 60 CHECK (retry_delay_s BETWEEN 10 AND 3600),
  priority        integer NOT NULL DEFAULT 1,
  status          text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  updated_by_id   bigint REFERENCES users(id),
  inserted_at     timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);

-- A rule's gateway; null: the active gateway with the lowest priority.
ALTER TABLE sms_voice_rules ADD COLUMN IF NOT EXISTS gateway_id bigint REFERENCES voice_gateways(id);
