-- HLR providers, rules and policies (spec §6.5, §13.24), build step 5.4.
SET search_path = sms, public;

-- Provider form fields of §6.5 the first schema did not hold.
ALTER TABLE hlr_providers
  ADD COLUMN extra_headers    text,
  ADD COLUMN post_data        text,
  -- Where each value sits in the provider's answer (§6.5 response-mapping captions).
  ADD COLUMN response_mapping jsonb NOT NULL DEFAULT '{"mcc":"mcc","mnc":"mnc","mccmnc":"mccmnc","oldMcc":"original.mcc","oldMnc":"original.mnc","oldMccmnc":"original.mccmnc","ported":"ported","errorCode":"error.code","errorString":"error.message","successCodes":"0","numberCheck":null,"dnidScore":null}',
  ADD COLUMN updated_by_id    bigint REFERENCES users(id);

-- Per-destination price per live lookup (§6.5 Rate / Import Rate / Export Rate); a destination
-- without a row uses the provider's default_rate. A country's "all networks" code prices the
-- whole country unless a network has its own row.
CREATE TABLE hlr_provider_rates (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hlr_provider_id bigint NOT NULL REFERENCES hlr_providers(id),
  mccmnc_id       bigint NOT NULL REFERENCES mccmnc(id),
  rate            numeric(12,6) NOT NULL CHECK (rate >= 0),
  updated_by_id   bigint REFERENCES users(id),
  inserted_at     timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);
CREATE UNIQUE INDEX hlr_provider_rates_live_uq ON hlr_provider_rates(hlr_provider_id, mccmnc_id) WHERE deleted_at IS NULL;

-- Last 24 hours per provider from the EDR store, refreshed every 5 minutes by the API (§13.24
-- live status and stats), so the provider list sorts and filters on them server-side.
CREATE TABLE hlr_provider_stats (
  hlr_provider_id bigint PRIMARY KEY REFERENCES hlr_providers(id),
  lookups         integer NOT NULL DEFAULT 0,
  live_lookups    integer NOT NULL DEFAULT 0,
  cached_lookups  integer NOT NULL DEFAULT 0,
  success_pct     numeric(5,1),
  avg_response_ms integer,
  cost_sys        numeric(14,4) NOT NULL DEFAULT 0,
  ported          integer NOT NULL DEFAULT 0,
  refreshed_at    timestamptz NOT NULL DEFAULT now()
);

-- Where an HLR rule runs on trunks that have not ordered it (copied to its targets on save).
ALTER TABLE hlr_rules
  ADD COLUMN insert_at   text NOT NULL DEFAULT 'bottom' CHECK (insert_at IN ('top','bottom'));

-- HLR policies (§13.24): per destination an ordered provider list or "auto", and cache times.
-- entries = [{code, mode, providerIds, minSuccessPct, cacheHoursPorted, cacheHoursNotPorted}],
-- code null = every other destination. Route rules point at a policy in hlr_action.policy_id.
CREATE TABLE hlr_policies (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  entries       jsonb NOT NULL DEFAULT '[]',
  updated_by_id bigint REFERENCES users(id),
  inserted_at   timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  deleted_at    timestamptz
);
CREATE UNIQUE INDEX hlr_policies_live_name_uq ON hlr_policies(lower(name)) WHERE deleted_at IS NULL;

-- Route rule HLR actions named a policy by text ("default"); they now point at policy 1 (the
-- generator's "Default" policy) by id.
UPDATE route_rules
   SET hlr_action = jsonb_build_object('policy_id', 1, 'customer_trunk_ids', COALESCE(hlr_action -> 'customer_trunk_ids', '[]'))
 WHERE hlr_action IS NOT NULL AND NOT hlr_action ? 'policy_id';
