-- Manual SOA option (§13.31): add a vendor invoice whatever its status, remove an automatic invoice
-- line (reason required), or a manual entry without an invoice file (SOA only, not in balances).
CREATE TABLE soa_adjustments (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id      bigint NOT NULL REFERENCES enterprises(id),
  action             text NOT NULL CHECK (action IN ('include_vendor_invoice','exclude_invoice','exclude_vendor_invoice','entry')),
  invoice_id         bigint REFERENCES invoices(id),
  vendor_invoice_id  bigint REFERENCES vendor_invoices(id),
  side               text CHECK (side IN ('customer','vendor')),
  kind               text CHECK (kind IN ('payment','credit_note','adjustment','opening_balance')),
  entry_date         date,
  amount             numeric(14,2),
  currency           char(3) REFERENCES currencies(iso),
  description        text,
  note               text,
  created_by_id      bigint REFERENCES users(id),
  inserted_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at         timestamptz,
  CHECK (action <> 'entry' OR (side IS NOT NULL AND kind IS NOT NULL AND entry_date IS NOT NULL AND amount IS NOT NULL)),
  CHECK (action <> 'exclude_invoice' OR invoice_id IS NOT NULL),
  CHECK (action NOT IN ('include_vendor_invoice','exclude_vendor_invoice') OR vendor_invoice_id IS NOT NULL)
);
CREATE INDEX soa_adjustments_enterprise_idx ON soa_adjustments(enterprise_id) WHERE deleted_at IS NULL;

-- SOA Report (§7): Queue SOA Export and Send Email runs, with the statement kept as it was (a sent
-- copy never changes).
CREATE TABLE soa_reports (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id      bigint NOT NULL REFERENCES enterprises(id),
  period_from        date NOT NULL,
  period_to          date NOT NULL,
  invoice_type       text NOT NULL CHECK (invoice_type IN ('all','auto','manual')),
  file_type          text NOT NULL CHECK (file_type IN ('excel','pdf')),
  purpose            text NOT NULL CHECK (purpose IN ('export','email')),
  status             text NOT NULL CHECK (status IN ('pending','inprogress','success','failed')),
  error              text,
  template_id        bigint REFERENCES email_templates(id),
  emailed_at         timestamptz,
  email_to           text[] NOT NULL DEFAULT '{}',
  snapshot           jsonb,
  closing_balance    numeric(14,2),
  currency           char(3),
  created_by_id      bigint REFERENCES users(id),
  inserted_at        timestamptz NOT NULL DEFAULT now(),
  finished_at        timestamptz
);
CREATE INDEX soa_reports_time_idx ON soa_reports(inserted_at DESC);
