-- Email Template (§11): name, type, subject and body with placeholders. Null business company =
-- shared by every company.
CREATE TABLE email_templates (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_company_id  bigint REFERENCES business_companies(id),
  name                 text NOT NULL,
  email_type           text NOT NULL CHECK (email_type IN ('customer_rate','invoice','low_balance','bind_down',
                         'customer_tech_info','trunk_change_info','soa_statement','rate_upload_notification',
                         'traffic_alert','auto_upload_rejected','trouble_ticket','send_soa')),
  subject              text NOT NULL,
  body                 text NOT NULL,
  updated_by_id        bigint REFERENCES users(id),
  inserted_at          timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz
);

