-- Market rate movements (spec §13.14), build step 5.15: when several top vendors move their rate for
-- the same destination within a few days, the move is recorded once, shown to account managers with
-- the affected clients, and handled (update rates, reroute, snooze, dismiss), with a log.
SET search_path = sms, public;

CREATE TABLE market_move_settings (
  id                 smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  cheapest_n         smallint NOT NULL DEFAULT 3,
  include_tier1      boolean NOT NULL DEFAULT true,
  window_days        smallint NOT NULL DEFAULT 7,
  min_vendors        smallint NOT NULL DEFAULT 2,
  min_change_pct     numeric(6,2) NOT NULL DEFAULT 3,
  lookback_days      smallint NOT NULL DEFAULT 30,
  urgent_change_pct  numeric(6,2) NOT NULL DEFAULT 10,
  urgent_days        smallint NOT NULL DEFAULT 7,
  target_margin_pct  numeric(6,2),
  digest_hour        smallint NOT NULL DEFAULT 7,
  last_digest_at     timestamptz,
  updated_by_id      bigint REFERENCES users(id),
  updated_at         timestamptz NOT NULL DEFAULT now()
);
INSERT INTO market_move_settings (id) VALUES (1);

CREATE TABLE market_moves (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mccmnc_id        bigint NOT NULL REFERENCES mccmnc(id),
  direction        text NOT NULL CHECK (direction IN ('up','down')),
  first_effective  timestamptz NOT NULL,
  last_effective   timestamptz NOT NULL,
  avg_change_pct   numeric(7,2) NOT NULL,
  moved_count      smallint NOT NULL,
  top_count        smallint NOT NULL,
  old_cost_usd     numeric(14,8),
  new_cost_usd     numeric(14,8),
  urgent           boolean NOT NULL DEFAULT false,
  state            text NOT NULL DEFAULT 'open' CHECK (state IN ('open','snoozed','handled','dismissed','expired')),
  snoozed_until    timestamptz,
  note             text,
  handled_by_id    bigint REFERENCES users(id),
  handled_at       timestamptz,
  affected_tables  integer NOT NULL DEFAULT 0,
  affected_clients integer NOT NULL DEFAULT 0,
  affected_am_ids  bigint[] NOT NULL DEFAULT '{}',
  volume_7d        integer NOT NULL DEFAULT 0,
  auto_applied     integer NOT NULL DEFAULT 0,
  detected_at      timestamptz NOT NULL DEFAULT now(),
  digested_at      timestamptz,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (mccmnc_id, direction, first_effective)
);
CREATE INDEX market_moves_state_idx ON market_moves (state);
CREATE INDEX market_moves_detected_idx ON market_moves (detected_at DESC);
CREATE INDEX market_moves_am_idx ON market_moves USING gin (affected_am_ids);

CREATE TABLE market_move_vendors (
  move_id         bigint NOT NULL REFERENCES market_moves(id),
  vendor_trunk_id bigint NOT NULL REFERENCES vendor_trunks(id),
  moved           boolean NOT NULL,
  old_rate_usd    numeric(14,8),
  new_rate_usd    numeric(14,8),
  effective_from  timestamptz,
  PRIMARY KEY (move_id, vendor_trunk_id)
);

CREATE TABLE market_move_log (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  move_id  bigint NOT NULL REFERENCES market_moves(id),
  at       timestamptz NOT NULL DEFAULT now(),
  user_id  bigint REFERENCES users(id),
  text     text NOT NULL
);
CREATE INDEX market_move_log_move_idx ON market_move_log (move_id);

-- Optional auto-apply per client or category (§13.14 "Auto-apply rule").
CREATE TABLE market_auto_rules (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id   bigint REFERENCES enterprises(id),
  category_id     bigint REFERENCES product_categories(id),
  direction       text NOT NULL DEFAULT 'increases' CHECK (direction IN ('increases','both')),
  min_margin_pct  numeric(6,2) NOT NULL,
  status          text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  updated_by_id   bigint REFERENCES users(id),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz,
  CHECK ((enterprise_id IS NULL) <> (category_id IS NULL))
);

-- Changes are found by the version that follows a closed one (valid_to = valid_from).
CREATE INDEX IF NOT EXISTS rate_lines_from_idx ON rate_lines (valid_from) WHERE sender_id IS NULL;
