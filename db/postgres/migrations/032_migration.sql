-- Migration Center (spec §13.22), build step 5.20: encrypted full export packages with single-use download
-- links, imports from another system (files kept for re-runs, dry-run report, the change that applied
-- them), saved column mappings per source system, and links from imported records to their old IDs.
SET search_path = sms, public;

CREATE TABLE migration_exports (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status               text NOT NULL DEFAULT 'running' CHECK (status IN ('running','done','failed')),
  includes_credentials boolean NOT NULL,
  with_passwords       boolean NOT NULL,
  rate_lines           text NOT NULL CHECK (rate_lines IN ('current','all','none')),
  file_path            text,
  size_bytes           bigint,
  manifest             jsonb,
  error                text,
  created_by_id        bigint REFERENCES users(id),
  inserted_at          timestamptz NOT NULL DEFAULT now(),
  finished_at          timestamptz
);

CREATE TABLE migration_links (
  token       text PRIMARY KEY,
  export_id   bigint NOT NULL REFERENCES migration_exports(id),
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz,
  created_by_id bigint REFERENCES users(id),
  inserted_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE migration_mappings (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_system  text NOT NULL,
  entity         text NOT NULL,
  name           text NOT NULL,
  columns        jsonb NOT NULL,
  built_in       boolean NOT NULL DEFAULT false,
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_system, entity, name)
);

CREATE TABLE migration_imports (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_system       text NOT NULL,
  status              text NOT NULL DEFAULT 'validated' CHECK (status IN ('validated','applied','failed')),
  input               jsonb NOT NULL,           -- settings and file contents, for re-runs
  report              jsonb NOT NULL,
  includes_credentials boolean NOT NULL DEFAULT false,
  change_id           bigint REFERENCES changes(id),
  created_by_id       bigint REFERENCES users(id),
  inserted_at         timestamptz NOT NULL DEFAULT now(),
  validated_at        timestamptz NOT NULL DEFAULT now(),
  applied_at          timestamptz
);

-- Old IDs of imported records, so EDRs and reports of the old platform can be linked to them.
CREATE TABLE migration_refs (
  source_system  text NOT NULL,
  entity         text NOT NULL,
  external_id    text NOT NULL,
  record_id      bigint NOT NULL,
  import_id      bigint REFERENCES migration_imports(id),
  PRIMARY KEY (source_system, entity, external_id)
);
CREATE INDEX migration_refs_import_idx ON migration_refs (import_id);

ALTER TABLE email_logs DROP CONSTRAINT IF EXISTS email_logs_email_type_check;
ALTER TABLE email_logs ADD CONSTRAINT email_logs_email_type_check CHECK (email_type IN ('send_rate','send_tech_info','invoice',
  'check_smtp','bind_down_alert','otp','forgot_password','auto_upload_rate','credit_alert','balance_alert','schedule_report_alert',
  'traffic_alert','auto_upload_rejected','daily_report','broadcast','trouble_ticket','send_soa','payment_confirmation',
  'invoice_acceptance','invoice_rejection','monitoring_alert','cleanup_summary','credential_transfer'));
ALTER TABLE changes DROP CONSTRAINT IF EXISTS changes_change_type_check;
ALTER TABLE changes ADD CONSTRAINT changes_change_type_check CHECK (change_type IN ('create','edit','clone','delete',
  'reorder','enable','disable','bulk','undo','import','cleanup'));
