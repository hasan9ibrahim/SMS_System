-- Switch utilities (spec §8), build step 5.8: e-mail logs, firewall, traffic alerts, SMS to voice,
-- broadcasts. Rate and tech-info notifications use customer trunks and rate tables as they are.
SET search_path = sms, public;

-- Email Logs (§8): one row per e-mail the platform sends (or fails to send).
CREATE TABLE email_logs (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id      bigint REFERENCES enterprises(id),
  customer_trunk_id  bigint REFERENCES customer_trunks(id),
  vendor_trunk_id    bigint REFERENCES vendor_trunks(id),
  email_type         text NOT NULL CHECK (email_type IN ('send_rate','send_tech_info','invoice','check_smtp',
                       'bind_down_alert','otp','forgot_password','auto_upload_rate','credit_alert','balance_alert',
                       'schedule_report_alert','traffic_alert','auto_upload_rejected','daily_report','broadcast',
                       'trouble_ticket','send_soa','payment_confirmation','invoice_acceptance','invoice_rejection')),
  status             text NOT NULL CHECK (status IN ('sent','failed')),
  rate_date          date,
  file_name          text,
  error              text,
  sender             text,
  to_addresses       text[] NOT NULL DEFAULT '{}',
  cc_addresses       text[] NOT NULL DEFAULT '{}',
  subject            text NOT NULL,
  body               text NOT NULL DEFAULT '',
  user_id            bigint REFERENCES users(id),             -- null = the platform
  inserted_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX email_logs_time_idx ON email_logs(inserted_at DESC);
CREATE INDEX email_logs_enterprise_idx ON email_logs(enterprise_id, inserted_at DESC);

-- Firewall (§8): filters = which listener a rule guards, with the brute-force threshold; rules =
-- banned or trusted addresses / ranges.
CREATE TABLE firewall_filters (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             text NOT NULL,
  listener         text NOT NULL CHECK (listener IN ('smpp','http','portal','all')),
  status           text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  failed_attempts  integer NOT NULL DEFAULT 5,
  window_seconds   integer NOT NULL DEFAULT 60,
  ban_minutes      integer NOT NULL DEFAULT 60,
  updated_by_id    bigint REFERENCES users(id),
  inserted_at      timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  deleted_at       timestamptz
);
CREATE UNIQUE INDEX firewall_filters_name_uq ON firewall_filters (lower(name)) WHERE deleted_at IS NULL;

CREATE TABLE firewall_rules (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list           text NOT NULL CHECK (list IN ('banned','trusted')),
  ip             cidr NOT NULL,
  filter_id      bigint NOT NULL REFERENCES firewall_filters(id),
  source         text NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','auto')),
  reason         text,
  hits           integer NOT NULL DEFAULT 0,
  last_hit_at    timestamptz,
  expires_at     timestamptz,
  created_by_id  bigint REFERENCES users(id),
  inserted_at    timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);
CREATE UNIQUE INDEX firewall_rules_live_uq ON firewall_rules (ip, filter_id) WHERE deleted_at IS NULL;
CREATE INDEX firewall_rules_ip_idx ON firewall_rules USING gist (ip inet_ops);

-- Traffic Alert (§8).
CREATE TABLE traffic_alerts (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 text NOT NULL,
  sample_count         integer NOT NULL,
  sample_minutes       integer NOT NULL,
  asr_threshold        numeric(5,2) NOT NULL,
  dlr_threshold        numeric(5,2) NOT NULL,
  margin_threshold     numeric(6,2) NOT NULL,
  customer_trunk_id    bigint NOT NULL REFERENCES customer_trunks(id),
  vendor_trunk_id      bigint REFERENCES vendor_trunks(id),
  sender_id            text,
  mccmnc               text,
  delay_threshold      numeric(8,2),
  notification_emails  text[] NOT NULL DEFAULT '{}',
  contact_email        text NOT NULL DEFAULT 'none' CHECK (contact_email IN ('none','commercial','technical','rates','finance')),
  template_id          bigint NOT NULL REFERENCES email_templates(id),
  status               text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  state                text NOT NULL DEFAULT 'unknown' CHECK (state IN ('ok','firing','too_few','unknown')),
  last_checked_at      timestamptz,
  last_triggered_at    timestamptz,
  last_values          jsonb,
  updated_by_id        bigint REFERENCES users(id),
  inserted_at          timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz
);

-- SMS To Voice (§8): matching SMS (e.g. OTP to landlines) become a voice call.
CREATE TABLE sms_voice_rules (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id      text,
  receiver_id    text,
  prefix         text,
  repeat_count   smallint NOT NULL DEFAULT 2 CHECK (repeat_count BETWEEN 1 AND 5),
  mccmnc         text,
  status         text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  updated_by_id  bigint REFERENCES users(id),
  inserted_at    timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);

-- Broadcast (§8): mass e-mail to partners; each e-mail is also an email_logs row.
CREATE TABLE broadcasts (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_company_id  bigint NOT NULL REFERENCES business_companies(id),
  sender               text NOT NULL,
  subject              text NOT NULL,
  body_html            text NOT NULL,
  contact_types        text[] NOT NULL,
  enterprise_types     text[] NOT NULL,
  enterprises          integer NOT NULL,
  addresses            integer NOT NULL,
  failed               integer NOT NULL DEFAULT 0,
  attachment_name      text,
  sent_by_id           bigint REFERENCES users(id),
  inserted_at          timestamptz NOT NULL DEFAULT now()
);

