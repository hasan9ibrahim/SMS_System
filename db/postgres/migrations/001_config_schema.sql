  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  iso           char(3) NOT NULL UNIQUE,
  name          text NOT NULL,
  symbol        text NOT NULL,
  inserted_at   timestamptz NOT NULL DEFAULT now(),
