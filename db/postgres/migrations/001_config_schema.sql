CREATE TABLE changes (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type   text NOT NULL,                              -- route_rule, rate_line, translation_rule, ...
  entity_ids    bigint[] NOT NULL,                          -- a bulk change touches many
  change_type   text NOT NULL CHECK (change_type IN ('create','edit','clone','delete','reorder','enable','disable','bulk','undo')),
  -- [{entity_id, field, before, after}]
  diff          jsonb NOT NULL,
  note          text,
  undo_of_id    bigint REFERENCES changes(id),
  user_id       bigint NOT NULL REFERENCES users(id),
  ip            inet,
  inserted_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX changes_entity_idx ON changes USING gin (entity_ids);
CREATE INDEX changes_user_idx ON changes(user_id, inserted_at DESC);
CREATE INDEX changes_type_time_idx ON changes(entity_type, inserted_at DESC);
