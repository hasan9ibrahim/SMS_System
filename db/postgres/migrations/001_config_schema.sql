-- SMS aggregation platform: configuration schema (PostgreSQL 16).
--
-- Written for reuse by the Elixir backend (Ecto conventions):
--   * plural snake_case tables, bigint identity ids, inserted_at / updated_at (timestamptz, UTC)
--   * created_by_id / updated_by_id reference users (spec §1 "Updated By / Updated Time")
--   * safe delete: deleted_at / deleted_by_id, rows are never hard-deleted (spec §13.29)
--   * money and rates are numeric, never float
-- EDRs live in ClickHouse (db/clickhouse/migrations), not here.

-- Tables live in schema "sms" (created by db/postgres/init); extensions stay in public.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;     -- fast %wildcard% / ILIKE filters (spec §13.25)
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;  -- rate-line validity overlap guard
CREATE SCHEMA IF NOT EXISTS sms;
SET search_path = sms, public;

