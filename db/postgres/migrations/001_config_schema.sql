CREATE TABLE route_rules (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                    text NOT NULL,
  priority                smallint NOT NULL CHECK (priority BETWEEN 1 AND 100),
  status                  text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  starts_at               timestamptz NOT NULL,
  stops_at                timestamptz NOT NULL,
  route_rule_group_id     bigint REFERENCES route_rule_groups(id),
  next_route_rule_group_id bigint REFERENCES route_rule_groups(id),
  continue_routing        text NOT NULL DEFAULT 'stop' CHECK (continue_routing IN ('yes','stop','next')),
  match_mode              text NOT NULL DEFAULT 'all' CHECK (match_mode IN ('all','any')),
  -- match side; *_mode = all | inclusive | exclusive, the array holds the list
  category_mode           text NOT NULL DEFAULT 'all' CHECK (category_mode IN ('all','inclusive','exclusive')),
  category_ids            bigint[] NOT NULL DEFAULT '{}',
  customer_trunk_mode     text NOT NULL DEFAULT 'all' CHECK (customer_trunk_mode IN ('all','inclusive','exclusive')),
  customer_trunk_ids      bigint[] NOT NULL DEFAULT '{}',
  mccmnc_mode             text NOT NULL DEFAULT 'all' CHECK (mccmnc_mode IN ('all','inclusive','exclusive')),
  mccmncs                 text[] NOT NULL DEFAULT '{}',      -- codes; a 3-digit code = whole country
  mccmnc_pattern          text,                              -- dynamic regex (§13.21)
  sender_pattern          text,
  sender_pattern_negate   boolean NOT NULL DEFAULT false,
  receiver_pattern        text,
  receiver_pattern_negate boolean NOT NULL DEFAULT false,
  content_pattern         text,
  content_pattern_negate  boolean NOT NULL DEFAULT false,
  sender_list_id          bigint REFERENCES number_lists(id),
  receiver_list_id        bigint REFERENCES number_lists(id),
  -- TPS condition (§13.8)
  tps_condition           jsonb,  -- {op, value, value2, tolerance_pct, scope, window_s, hold_s, release_pct}
  -- Revenue condition (§13.9)
  revenue_condition       jsonb,  -- {type: per_message|accumulated, op, value, value2, scope, period, min_margin}
  -- action side
  route_type              text NOT NULL CHECK (route_type IN ('block','static','dynamic','qbr')),
