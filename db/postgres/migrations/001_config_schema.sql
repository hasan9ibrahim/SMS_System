-- Exchange rate history: units of `iso` per 1 USD; latest valid_from wins.
CREATE TABLE currency_rates (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  iso           char(3) NOT NULL REFERENCES currencies(iso),
