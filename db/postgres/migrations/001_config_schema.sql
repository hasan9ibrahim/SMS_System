-- Customer (sell) tables are attached to customer trunks; every vendor trunk has
-- exactly one vendor (buy) table, so the Rate Manager treats both alike (§13.12).
CREATE TABLE rate_tables (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind                text NOT NULL CHECK (kind IN ('customer','vendor')),
  name                text NOT NULL,
  product_category_id bigint NOT NULL REFERENCES product_categories(id),
  currency            char(3) NOT NULL REFERENCES currencies(iso),
  vendor_trunk_id     bigint UNIQUE REFERENCES vendor_trunks(id),
  description         text,
  created_by_id       bigint REFERENCES users(id),
  updated_by_id       bigint REFERENCES users(id),
  inserted_at         timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  deleted_at          timestamptz,
  deleted_by_id       bigint REFERENCES users(id),
  CHECK ((kind = 'vendor') = (vendor_trunk_id IS NOT NULL))
);
CREATE INDEX rate_tables_name_trgm ON rate_tables USING gin (name gin_trgm_ops);

-- Ordered rate tables of a customer trunk; first match wins (spec §5.4).
CREATE TABLE customer_trunk_rate_tables (
  customer_trunk_id bigint NOT NULL REFERENCES customer_trunks(id),
  rate_table_id     bigint NOT NULL REFERENCES rate_tables(id),
  position          smallint NOT NULL,
  PRIMARY KEY (customer_trunk_id, rate_table_id)
);
CREATE INDEX ctrt_rate_table_idx ON customer_trunk_rate_tables(rate_table_id);

-- Rate lines with full history: a change closes the old line (valid_to) and
-- opens a new one; valid_to IS NULL means open-ended. Future valid_from = scheduled.
CREATE TABLE rate_lines (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rate_table_id     bigint NOT NULL REFERENCES rate_tables(id),
  mccmnc_id         bigint NOT NULL REFERENCES mccmnc(id),
  mccmnc            text NOT NULL,                           -- denormalised for filters
  dial_code         text,
  sender_id         text,
  rate              numeric(12,6) NOT NULL CHECK (rate >= 0),
  currency          char(3) NOT NULL REFERENCES currencies(iso),
  valid_from        timestamptz NOT NULL,
  valid_to          timestamptz,
  stated_valid_from timestamptz,                             -- RN date when back-dated (§13.32)
  is_blocked        boolean NOT NULL DEFAULT false,
  change_type       text NOT NULL CHECK (change_type IN ('new','same','increase','decrease','closed')),
  rate_note         text,
  created_by_id     bigint REFERENCES users(id),
  updated_by_id     bigint REFERENCES users(id),
  inserted_at       timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (valid_to IS NULL OR valid_to > valid_from),
  -- No two versions of the same destination (and sender) may overlap in time.
  CONSTRAINT rate_lines_no_overlap EXCLUDE USING gist (
    rate_table_id WITH =, mccmnc_id WITH =, tstzrange(valid_from, valid_to) WITH &&
  ) WHERE (sender_id IS NULL),
  CONSTRAINT rate_lines_sender_no_overlap EXCLUDE USING gist (
    rate_table_id WITH =, mccmnc_id WITH =, sender_id WITH =, tstzrange(valid_from, valid_to) WITH &&
  ) WHERE (sender_id IS NOT NULL)
);
CREATE INDEX rate_lines_table_mccmnc_idx ON rate_lines(rate_table_id, mccmnc, valid_from);
CREATE INDEX rate_lines_mccmnc_idx ON rate_lines(mccmnc, valid_from);
CREATE INDEX rate_lines_open_idx ON rate_lines(rate_table_id) WHERE valid_to IS NULL;

