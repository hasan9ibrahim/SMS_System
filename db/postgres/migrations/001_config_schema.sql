  is_account_manager    boolean NOT NULL DEFAULT false,
  is_team_lead          boolean NOT NULL DEFAULT false,
  is_admin              boolean NOT NULL DEFAULT false,
  status                text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
