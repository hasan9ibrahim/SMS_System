-- Product reference data screens (build step 5, spec §6.1): who changed what, safe delete
-- (§13.29) on categories, MCCMNC codes, dial-code profiles and prefixes, the "Original MNC"
-- column, Master Table profiles as records, and the MO reference book.
SET search_path = sms, public;

-- Product categories: archived names may be reused.
ALTER TABLE product_categories ADD COLUMN updated_by_id bigint REFERENCES users(id);
ALTER TABLE product_categories DROP CONSTRAINT product_categories_name_key;
CREATE UNIQUE INDEX product_categories_name_live ON product_categories (lower(name)) WHERE deleted_at IS NULL;

ALTER TABLE countries ADD COLUMN updated_by_id bigint REFERENCES users(id);

-- MCCMNC codes: a code is unique among live codes; an archived code can be added again.
ALTER TABLE mccmnc
  ADD COLUMN original_mnc  text,
  ADD COLUMN updated_by_id bigint REFERENCES users(id),
  ADD COLUMN deleted_at    timestamptz;
ALTER TABLE mccmnc DROP CONSTRAINT mccmnc_mccmnc_key;
CREATE UNIQUE INDEX mccmnc_code_live ON mccmnc (mccmnc) WHERE deleted_at IS NULL;
CREATE INDEX mccmnc_code_idx ON mccmnc (mccmnc);

-- Master Table profiles. dial_codes.profile keeps the name (renames cascade).
CREATE TABLE dial_code_profiles (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL UNIQUE,
  updated_by_id bigint REFERENCES users(id),
  inserted_at   timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  deleted_at    timestamptz
);
INSERT INTO dial_code_profiles (id, name) VALUES (1, 'All');
SELECT setval(pg_get_serial_sequence('dial_code_profiles', 'id'), 1);
INSERT INTO dial_code_profiles (name)
  SELECT DISTINCT profile FROM dial_codes WHERE profile <> 'All' ORDER BY 1;

ALTER TABLE dial_codes
  ADD COLUMN updated_by_id bigint REFERENCES users(id),
  ADD COLUMN updated_at    timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN deleted_at    timestamptz,
  ADD CONSTRAINT dial_codes_profile_fkey FOREIGN KEY (profile) REFERENCES dial_code_profiles(name) ON UPDATE CASCADE;
ALTER TABLE dial_codes DROP CONSTRAINT dial_codes_profile_prefix_key;
CREATE UNIQUE INDEX dial_codes_prefix_live ON dial_codes (profile, prefix) WHERE deleted_at IS NULL;
CREATE INDEX dial_codes_mccmnc_idx ON dial_codes (mccmnc_id);

-- MO reference book (§6.1): two-way and MO billing numbers of customer trunks.
CREATE TABLE mo_numbers (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_trunk_id  bigint NOT NULL REFERENCES customer_trunks(id),
  number             text NOT NULL CHECK (number ~ '^[0-9]{3,20}$'),
  keyword            text,                                   -- NULL = any message to the number
  rate               numeric(12,6) NOT NULL CHECK (rate >= 0),
  vendor_rate        numeric(12,6) CHECK (vendor_rate >= 0),
  currency           char(3) NOT NULL REFERENCES currencies(iso),
  mccmnc_id          bigint REFERENCES mccmnc(id),
  setup_charge       numeric(12,4) NOT NULL DEFAULT 0 CHECK (setup_charge >= 0),
  fix_charge         numeric(12,4) NOT NULL DEFAULT 0 CHECK (fix_charge >= 0),
  created_by_id      bigint REFERENCES users(id),
  updated_by_id      bigint REFERENCES users(id),
  inserted_at        timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  deleted_at         timestamptz
);
CREATE UNIQUE INDEX mo_numbers_live ON mo_numbers (number, coalesce(lower(keyword), '')) WHERE deleted_at IS NULL;
CREATE INDEX mo_numbers_trunk_idx ON mo_numbers (customer_trunk_id);

-- Imports (§6.1) are one change each, with their own type in the change history.
ALTER TABLE changes DROP CONSTRAINT changes_change_type_check;
ALTER TABLE changes ADD CONSTRAINT changes_change_type_check
  CHECK (change_type IN ('create','edit','clone','delete','reorder','enable','disable','bulk','undo','import'));
