-- Reports (spec §10, §13.15), build step 5.10: scheduled reports and daily traffic alerts. Report
-- figures come from the EDR store; saved Master Report views use saved_views (list master_report).
SET search_path = sms, public;

-- Schedule Report (§10): a preset or saved view e-mailed on a CRON schedule (UTC).
CREATE TABLE scheduled_reports (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 text NOT NULL,
  description          text,
  template_kind        text NOT NULL CHECK (template_kind IN ('preset','view')),
  preset_key           text,
  view_id              bigint REFERENCES saved_views(id) ON DELETE SET NULL,
  status               text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  business_company_id  bigint NOT NULL REFERENCES business_companies(id),
  notification_emails  text[] NOT NULL,
  cron_interval        text NOT NULL CHECK (cron_interval IN ('minute','hourly','daily','weekly','monthly')),
  cron_frequency       smallint NOT NULL DEFAULT 1 CHECK (cron_frequency BETWEEN 1 AND 59),
  cron_expression      text NOT NULL,
  file_type            text NOT NULL DEFAULT 'excel' CHECK (file_type IN ('csv','excel','pdf')),
  email_body           text NOT NULL,
  next_run_at          timestamptz,
  last_run_at          timestamptz,
  last_status          text CHECK (last_status IN ('sent','failed')),
  last_error           text,
  updated_by_id        bigint REFERENCES users(id),
  inserted_at          timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz,
  CHECK (template_kind <> 'preset' OR preset_key IS NOT NULL)
);
CREATE UNIQUE INDEX scheduled_reports_name_uq ON scheduled_reports (lower(name)) WHERE deleted_at IS NULL;

-- Daily Traffic Alert (§10): yesterday's traffic summary e-mailed to a partner.
CREATE TABLE daily_traffic_alerts (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 text NOT NULL,
  status               text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  business_company_id  bigint REFERENCES business_companies(id),
  contact_type         text NOT NULL CHECK (contact_type IN ('commercial','technical','rates','finance')),
  enterprise_id        bigint NOT NULL REFERENCES enterprises(id),
  send_hour            smallint NOT NULL DEFAULT 6 CHECK (send_hour BETWEEN 0 AND 23),
  email_body           text NOT NULL,
  last_sent_at         timestamptz,
  updated_by_id        bigint REFERENCES users(id),
  inserted_at          timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz
);
CREATE UNIQUE INDEX daily_traffic_alerts_name_uq ON daily_traffic_alerts (lower(name)) WHERE deleted_at IS NULL;
