-- Incoming vendor rate notifications (spec §13.13 A, §13.32), build step 5.14: each vendor rate
-- e-mail or upload becomes an RN for one vendor trunk, with its lines compared to the current rate
-- and checked against live traffic; decisions, replies to the vendor and settings.
SET search_path = sms, public;

CREATE TABLE rate_notifications (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference           text NOT NULL UNIQUE,
  vendor_id           bigint REFERENCES enterprises(id),
  vendor_trunk_id     bigint REFERENCES vendor_trunks(id),
  rate_table_id       bigint REFERENCES rate_tables(id),
  currency            text,
  source              text NOT NULL CHECK (source IN ('email','upload')),
  mailbox             text,
  from_address        text,
  subject             text,
  body                text,
  file_name           text,
  file_content        text,
  received_at         timestamptz NOT NULL DEFAULT now(),
  effective_from      timestamptz,
  status              text NOT NULL CHECK (status IN ('pending','accepted','partly_accepted','rejected','failed','unmatched')),
  match_reason        text,
  notice_days         smallint NOT NULL DEFAULT 0,
  columns             jsonb NOT NULL DEFAULT '[]',   -- [{header, field}]
  file_errors         jsonb NOT NULL DEFAULT '[]',   -- [{line, message}]
  -- counts, refreshed by the check
  lines               integer NOT NULL DEFAULT 0,
  new_lines           integer NOT NULL DEFAULT 0,
  increases           integer NOT NULL DEFAULT 0,
  decreases           integer NOT NULL DEFAULT 0,
  unchanged           integer NOT NULL DEFAULT 0,
  closed              integer NOT NULL DEFAULT 0,
  errors              integer NOT NULL DEFAULT 0,
  flagged             integer NOT NULL DEFAULT 0,
  notice_breaches     integer NOT NULL DEFAULT 0,
  backdated           integer NOT NULL DEFAULT 0,
  turns_negative      integer NOT NULL DEFAULT 0,
  affected_rate_table_ids bigint[] NOT NULL DEFAULT '{}',
  checked_at          timestamptz,
  auto_accepted       boolean NOT NULL DEFAULT false,
  decided_by_id       bigint REFERENCES users(id),
  decided_at          timestamptz,
  reject_reason       text,
  change_id           bigint,
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX rate_notifications_received_idx ON rate_notifications (received_at DESC);
CREATE INDEX rate_notifications_vendor_idx ON rate_notifications (vendor_id);
CREATE INDEX rate_notifications_status_idx ON rate_notifications (status);

CREATE TABLE rate_notification_lines (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rn_id            bigint NOT NULL REFERENCES rate_notifications(id),
  line_no          integer NOT NULL,
  mccmnc_id        bigint REFERENCES mccmnc(id),
  mccmnc           text NOT NULL,
  sender_id        text,
  current_line_id  bigint,
  current_rate     numeric(12,6),
  new_rate         numeric(12,6),            -- NULL when the destination is closed
  change_type      text NOT NULL CHECK (change_type IN ('new','increase','decrease','unchanged','closed')),
  stated_from      timestamptz NOT NULL,
  applied_from     timestamptz NOT NULL,
  live_traffic     boolean NOT NULL DEFAULT false,
  flagged          boolean NOT NULL DEFAULT false,
  notice_breach    boolean NOT NULL DEFAULT false,
  backdated        boolean NOT NULL DEFAULT false,
  traffic_1h       integer NOT NULL DEFAULT 0,
  traffic_24h      integer NOT NULL DEFAULT 0,
  traffic_7d       integer NOT NULL DEFAULT 0,
  sent_between     integer NOT NULL DEFAULT 0,
  cost_between     numeric(14,4) NOT NULL DEFAULT 0,
  affected_customers text,
  margin_now_pct   numeric(7,1),
  margin_new_pct   numeric(7,1),
  turns_negative   boolean NOT NULL DEFAULT false,
  decision         text NOT NULL DEFAULT 'pending' CHECK (decision IN ('pending','accepted','rejected')),
  reject_reason    text,
  UNIQUE (rn_id, line_no)
);
CREATE INDEX rate_notification_lines_rn_idx ON rate_notification_lines (rn_id);

CREATE TABLE rate_notification_replies (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rn_id        bigint NOT NULL REFERENCES rate_notifications(id),
  kind         text NOT NULL CHECK (kind IN ('successful','failed','rejected')),
  to_addresses text[] NOT NULL DEFAULT '{}',
  subject      text NOT NULL,
  body         text NOT NULL,
  status       text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','sent','failed')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  sent_at      timestamptz,
  sent_by_id   bigint REFERENCES users(id)
);
CREATE INDEX rate_notification_replies_rn_idx ON rate_notification_replies (rn_id);

CREATE TABLE rate_notification_log (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rn_id    bigint NOT NULL REFERENCES rate_notifications(id),
  at       timestamptz NOT NULL DEFAULT now(),
  user_id  bigint REFERENCES users(id),
  text     text NOT NULL
);
CREATE INDEX rate_notification_log_rn_idx ON rate_notification_log (rn_id);

-- One row of global settings (§13.32).
CREATE TABLE rn_settings (
  id              smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  live_window     text NOT NULL DEFAULT '24h' CHECK (live_window IN ('1h','24h','7d')),
  min_messages    integer NOT NULL DEFAULT 1,
  reminder_days   smallint NOT NULL DEFAULT 2,
  auto_accept     boolean NOT NULL DEFAULT false,
  reply_successful text NOT NULL DEFAULT 'auto' CHECK (reply_successful IN ('auto','confirm','off')),
  reply_failed    text NOT NULL DEFAULT 'auto' CHECK (reply_failed IN ('auto','confirm','off')),
  reply_rejected  text NOT NULL DEFAULT 'confirm' CHECK (reply_rejected IN ('auto','confirm','off')),
  updated_by_id   bigint REFERENCES users(id),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
INSERT INTO rn_settings (id) VALUES (1);

-- Per-vendor overrides and the remembered column mapping (§13.13 "read any layout").
CREATE TABLE vendor_rn_settings (
  enterprise_id    bigint PRIMARY KEY REFERENCES enterprises(id),
  auto_accept      boolean,
  reply_successful text CHECK (reply_successful IN ('auto','confirm','off')),
  reply_failed     text CHECK (reply_failed IN ('auto','confirm','off')),
  reply_rejected   text CHECK (reply_rejected IN ('auto','confirm','off')),
  reply_to         text[] NOT NULL DEFAULT '{}',
  mapping          jsonb,
  updated_by_id    bigint REFERENCES users(id),
  updated_at       timestamptz NOT NULL DEFAULT now()
);
