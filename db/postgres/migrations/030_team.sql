-- Team activity and performance (spec §13.18), build step 5.18: monthly targets per user, pages opened
-- (pages most used, the page a user is on now), and the Team report as a scheduled report template.
SET search_path = sms, public;

CREATE TABLE user_targets (
  user_id         bigint NOT NULL REFERENCES users(id),
  month           date NOT NULL CHECK (extract(day FROM month) = 1),
  revenue_target  numeric(14,2) CHECK (revenue_target >= 0),   -- platform currency
  margin_target   numeric(14,2) CHECK (margin_target >= 0),
  updated_by_id   bigint REFERENCES users(id),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, month)
);

CREATE TABLE page_views (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id  bigint NOT NULL REFERENCES users(id),
  path     text NOT NULL,
  at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX page_views_user_at_idx ON page_views (user_id, at DESC);

CREATE INDEX IF NOT EXISTS changes_user_at_idx ON changes (user_id, inserted_at DESC);
CREATE INDEX IF NOT EXISTS user_sessions_user_idx ON user_sessions (user_id, logged_in_at DESC);

ALTER TABLE scheduled_reports DROP CONSTRAINT IF EXISTS scheduled_reports_template_kind_check;
ALTER TABLE scheduled_reports ADD CONSTRAINT scheduled_reports_template_kind_check
  CHECK (template_kind IN ('preset','view','team'));
ALTER TABLE scheduled_reports
  ADD COLUMN team_department_id bigint REFERENCES departments(id),
  ADD COLUMN team_period text CHECK (team_period IN ('today','yesterday','last_24_hours','last_7_days','this_week','last_week','this_month','last_month'));
