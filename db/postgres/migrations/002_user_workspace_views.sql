-- User preferences, open page tabs and saved filter views (build step 3, app shell).
SET search_path = sms, public;

-- UI preferences next to the existing users.theme column (§13.3, §13.5, §15.2).
ALTER TABLE users
  ADD COLUMN open_in_new_tab boolean NOT NULL DEFAULT true,
  ADD COLUMN animations      boolean NOT NULL DEFAULT true;

-- Open page tabs, restored after re-login per user (§13.5). Page state (filters, sort)
-- travels in each tab's path; scroll position stays in the browser.
CREATE TABLE user_workspaces (
  user_id       bigint PRIMARY KEY REFERENCES users(id),
  tabs          jsonb NOT NULL DEFAULT '[]',
  active_tab_id text,
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- Saved views (§13.25, decided 2026-10-16): private to the owner, optionally shared
-- read-only with chosen users. No department- or company-wide sharing.
CREATE TABLE saved_views (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list        text NOT NULL,
  name        text NOT NULL,
  owner_id    bigint NOT NULL REFERENCES users(id),
  state       jsonb NOT NULL,                 -- {filter, search, sort, columns}
  inserted_at timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_id, list, name)
);

CREATE TABLE saved_view_shares (
  saved_view_id bigint NOT NULL REFERENCES saved_views(id) ON DELETE CASCADE,
  user_id       bigint NOT NULL REFERENCES users(id),
  PRIMARY KEY (saved_view_id, user_id)
);
CREATE INDEX saved_view_shares_user_idx ON saved_view_shares(user_id);

-- Undo lookups: "was this change undone?" and "later changes to the same record".
CREATE INDEX changes_undo_of_idx ON changes(undo_of_id) WHERE undo_of_id IS NOT NULL;
