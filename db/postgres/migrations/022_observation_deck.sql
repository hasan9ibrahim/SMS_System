-- Observation Deck (spec §9), build step 5.9: EDR templates, EDR / failed EDR downloads, repush
-- requests, trunk bind status and SMPP sessions (§13.1), signaling captures. EDRs themselves live in
-- ClickHouse; these are the configuration and job tables around them.
SET search_path = sms, public;

-- EDR Template (§9.2): a saved EDR column set.
CREATE TABLE edr_templates (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL,
  columns        text[] NOT NULL CHECK (cardinality(columns) BETWEEN 1 AND 120),
  updated_by_id  bigint REFERENCES users(id),
  inserted_at    timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);
CREATE UNIQUE INDEX edr_templates_name_uq ON edr_templates (lower(name)) WHERE deleted_at IS NULL;

-- EDR Download / Failed EDR Download (§9.2, §12.4): background exports.
CREATE TABLE edr_downloads (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind             text NOT NULL CHECK (kind IN ('edr','failed_edr')),
  status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','inprogress','success','failed','cancelled')),
  file_type        text NOT NULL CHECK (file_type IN ('csv','xlsx')),
  file_name        text,
  file_path        text,                                   -- where the job wrote the file
  progress         smallint NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
  row_count        bigint,
  size_bytes       bigint,
  query            jsonb NOT NULL,                         -- filter, search, sort
  columns          text[] NOT NULL,
  template_id      bigint REFERENCES edr_templates(id),
  template_name    text,
  filter_summary   text NOT NULL DEFAULT '',
  error            text,
  requested_by_id  bigint REFERENCES users(id),
  requested_at     timestamptz NOT NULL DEFAULT now(),
  finished_at      timestamptz
);
CREATE INDEX edr_downloads_time_idx ON edr_downloads (kind, requested_at DESC);

-- Repush Request (§9.1, §9.2): selected EDRs re-sent on another vendor trunk.
CREATE TABLE repush_requests (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_trunk_id  bigint NOT NULL REFERENCES vendor_trunks(id),
  edr_count        integer NOT NULL,
  skipped          integer NOT NULL DEFAULT 0,
  status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','done')),
  delivered        integer NOT NULL DEFAULT 0,
  failed           integer NOT NULL DEFAULT 0,
  created_by_id    bigint REFERENCES users(id),
  inserted_at      timestamptz NOT NULL DEFAULT now()
);

-- Network Status (§9.2, §12.4): live bind status per trunk, kept by the switch (the mock's
-- simulator in this phase). Stopped = a user pressed Stop; it stays down until Start.
CREATE TABLE trunk_binds (
  side            text NOT NULL CHECK (side IN ('customer','vendor')),
  trunk_id        bigint NOT NULL,
  status          text NOT NULL CHECK (status IN ('online','offline','stopped')),
  connections     smallint NOT NULL DEFAULT 0,
  queue           integer,                                 -- vendors only
  tps             real NOT NULL DEFAULT 0,
  since           timestamptz NOT NULL DEFAULT now(),
  changed_by_id   bigint REFERENCES users(id),
  PRIMARY KEY (side, trunk_id)
);

-- SMPP sessions of a trunk (§13.1: receipts go back on the session and IP the message came from).
CREATE TABLE bind_sessions (
  session_id        text PRIMARY KEY,
  side              text NOT NULL CHECK (side IN ('customer','vendor')),
  trunk_id          bigint NOT NULL,
  ip                inet NOT NULL,
  port              integer NOT NULL,
  bind_type         text NOT NULL CHECK (bind_type IN ('TX','RX','TR')),
  since             timestamptz NOT NULL DEFAULT now(),
  submitted         integer NOT NULL DEFAULT 0,
  receipts_pending  integer NOT NULL DEFAULT 0
);
CREATE INDEX bind_sessions_trunk_idx ON bind_sessions (side, trunk_id);

-- Signaling Deck and PCAP Trace (§9.2): SMPP captures. The pcap is built from the capture's
-- parameters when downloaded (fake data only).
CREATE TABLE signaling_captures (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name             text NOT NULL,
  ip_filter             cidr,
  status                text NOT NULL DEFAULT 'running' CHECK (status IN ('running','done','failed','stopped')),
  size_bytes            bigint NOT NULL DEFAULT 0,
  packets               integer NOT NULL DEFAULT 0,
  max_duration_seconds  integer NOT NULL,
  max_file_size_bytes   bigint NOT NULL,
  started_by_id         bigint REFERENCES users(id),
  started_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);

