-- Staff sign-in (backend step 9, contract v0.96.0, §13.28). Product owner decisions 2026-10-25:
--
-- 1. Every login asks for a 2FA code: the authenticator app when the user has one, otherwise a code e-mailed to the
--    user. Only an administrator can turn the code off for a user (OTP verification Off); new users get e-mail.
-- 2. Sessions end after 8 hours without activity and 24 hours after sign-in at most.
--
-- Five wrong passwords in a row lock a staff user for 15 minutes, as for portal users.

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS failed_logins smallint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS locked_until timestamptz;

ALTER TABLE users ALTER COLUMN otp_method SET DEFAULT 'email';
UPDATE users SET otp_method = 'email' WHERE otp_method = 'off' AND NOT totp_enabled;

-- A started sign-in waiting for its code: found by a hash of the opaque challenge, 10 minutes and 5 tries.
CREATE TABLE IF NOT EXISTS sign_in_challenges (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash    text NOT NULL UNIQUE,
  user_id       bigint NOT NULL REFERENCES users(id),
  method        text NOT NULL CHECK (method IN ('authenticator', 'email')),
  code_hash     text,
  tries         smallint NOT NULL DEFAULT 0,
  ip            inet NOT NULL,
  user_agent    text NOT NULL DEFAULT '',
  created_at    timestamptz NOT NULL DEFAULT now(),
  sent_at       timestamptz,
  expires_at    timestamptz NOT NULL,
  used_at       timestamptz
);
CREATE INDEX IF NOT EXISTS sign_in_challenges_user_idx ON sign_in_challenges (user_id, created_at DESC);

-- 'replaced': ended by a new sign-in of a user without Allow Multiple Login.
ALTER TABLE user_sessions DROP CONSTRAINT IF EXISTS user_sessions_end_reason_check;
ALTER TABLE user_sessions ADD CONSTRAINT user_sessions_end_reason_check
  CHECK (end_reason IN ('logout', 'forced', 'expired', 'password_change', 'replaced'));
