-- Advanced LCR module (spec §13.23), build step 5.16: LCR profiles reused by Least cost route rules,
-- and change alerts when a destination's top LCR vendor changes or its cheapest cost moves.
SET search_path = sms, public;

CREATE TABLE lcr_profiles (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 text NOT NULL,
  description          text,
  status               text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  vendor_trunk_mode    text NOT NULL DEFAULT 'all' CHECK (vendor_trunk_mode IN ('all','inclusive','exclusive')),
  vendor_trunk_ids     bigint[] NOT NULL DEFAULT '{}',
  tiers                text[] NOT NULL DEFAULT '{}',
  min_asr              numeric(5,1),
  min_dlr              numeric(5,1),
  max_delay_s          numeric(8,1),
  max_rate             numeric(12,6),
  vendor_count         smallint NOT NULL DEFAULT 3 CHECK (vendor_count BETWEEN 1 AND 10),
  split                text NOT NULL DEFAULT 'top_down' CHECK (split IN ('top_down','percentage')),
  shares               smallint[] NOT NULL DEFAULT '{}',
  tie_breaker          text NOT NULL DEFAULT 'quality' CHECK (tie_breaker IN ('quality','cost')),
  exclude_at_tps_limit boolean NOT NULL DEFAULT true,
  quality_weighted     boolean NOT NULL DEFAULT false,
  weights              jsonb NOT NULL DEFAULT '{"cost": 60, "asr": 10, "dlr": 25, "delay": 5}',
  updated_by_id        bigint REFERENCES users(id),
  inserted_at          timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz
);
CREATE UNIQUE INDEX lcr_profiles_name_uq ON lcr_profiles (lower(name)) WHERE deleted_at IS NULL;

ALTER TABLE route_rules ADD COLUMN lcr_profile_id bigint REFERENCES lcr_profiles(id);
CREATE INDEX route_rules_lcr_profile_idx ON route_rules (lcr_profile_id) WHERE lcr_profile_id IS NOT NULL;

-- The cheapest vendor and cost per destination at the last check, and the changes found.
CREATE TABLE lcr_snapshot (
  mccmnc_id        bigint PRIMARY KEY REFERENCES mccmnc(id),
  vendor_trunk_id  bigint REFERENCES vendor_trunks(id),
  cost_usd         numeric(14,8),
  checked_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE lcr_changes (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mccmnc_id         bigint NOT NULL REFERENCES mccmnc(id),
  kind              text NOT NULL CHECK (kind IN ('top_changed','cost_moved')),
  old_vendor_id     bigint REFERENCES vendor_trunks(id),
  new_vendor_id     bigint REFERENCES vendor_trunks(id),
  old_cost_usd      numeric(14,8),
  new_cost_usd      numeric(14,8),
  change_pct        numeric(7,2),
  detected_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX lcr_changes_detected_idx ON lcr_changes (detected_at DESC);

CREATE TABLE lcr_alert_settings (
  id             smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  enabled        boolean NOT NULL DEFAULT true,
  cost_move_pct  numeric(6,2) NOT NULL DEFAULT 5,
  top_changed    boolean NOT NULL DEFAULT true,
  updated_by_id  bigint REFERENCES users(id),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
