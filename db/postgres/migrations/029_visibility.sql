-- Account manager visibility mode (spec §13.17), build step 5.17: policies that mask others' enterprises
-- and trunks and hide chosen data, their assignment to all account managers, a department or a user,
-- and lasting shares or temporary access to an enterprise. Changes are written to the Audit Trail.
SET search_path = sms, public;

CREATE TABLE visibility_policies (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL,
  description    text,
  status         text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  mask_others    boolean NOT NULL DEFAULT true,
  include_team   boolean NOT NULL DEFAULT false,
  -- {"margin": {"others": "hide", "own": "show"}, ...}: show / hide / band per item (contract VisibilityItems).
  items          jsonb NOT NULL,
  -- {"marginLowPct": 5, "marginHighPct": 20, "revenueHideAbove": null, "costTrafficDays": null}
  thresholds     jsonb NOT NULL,
  updated_by_id  bigint REFERENCES users(id),
  inserted_at    timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);
CREATE UNIQUE INDEX visibility_policies_name_uq ON visibility_policies (lower(name)) WHERE deleted_at IS NULL;

-- One assignment per target; a user's own wins over their department's, which wins over all_ams.
CREATE TABLE visibility_assignments (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_id      bigint NOT NULL REFERENCES visibility_policies(id),
  target_type    text NOT NULL CHECK (target_type IN ('all_ams','department','user')),
  target_id      bigint,
  created_by_id  bigint REFERENCES users(id),
  inserted_at    timestamptz NOT NULL DEFAULT now(),
  CHECK ((target_type = 'all_ams') = (target_id IS NULL))
);
CREATE UNIQUE INDEX visibility_assignments_target_uq ON visibility_assignments (target_type, COALESCE(target_id, 0));

-- Lasting shares (expires_at null) and temporary access to one enterprise.
CREATE TABLE visibility_grants (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        bigint NOT NULL REFERENCES users(id),
  enterprise_id  bigint NOT NULL REFERENCES enterprises(id),
  expires_at     timestamptz,
  reason         text NOT NULL,
  granted_by_id  bigint REFERENCES users(id),
  inserted_at    timestamptz NOT NULL DEFAULT now(),
  revoked_at     timestamptz,
  revoked_by_id  bigint REFERENCES users(id)
);
CREATE INDEX visibility_grants_user_idx ON visibility_grants (user_id) WHERE revoked_at IS NULL;

