-- Set-password links (team trial round 11, §13.28): an administrator e-mails users a single-use link that works for
-- 72 hours; it opens the Set Password screen and never signs anyone in. Only the token's SHA-256 is kept to check
-- the link. The token itself is kept encrypted only until the e-mail job has sent it (the logged e-mail shows a
-- placeholder), then cleared.
CREATE TABLE IF NOT EXISTS password_links (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        bigint NOT NULL REFERENCES users(id),
  token_hash     text NOT NULL UNIQUE,
  token_enc      text,
  email_log_id   bigint REFERENCES email_logs(id) ON DELETE SET NULL,
  expires_at     timestamptz NOT NULL,
  used_at        timestamptz,
  created_by_id  bigint REFERENCES users(id),
  inserted_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS password_links_user_idx ON password_links (user_id);
CREATE INDEX IF NOT EXISTS password_links_email_idx ON password_links (email_log_id);

-- The e-mail that carries the link.
ALTER TABLE email_logs DROP CONSTRAINT IF EXISTS email_logs_email_type_check;
ALTER TABLE email_logs ADD CONSTRAINT email_logs_email_type_check CHECK (email_type IN ('send_rate','send_tech_info','invoice',
  'check_smtp','bind_down_alert','otp','forgot_password','auto_upload_rate','credit_alert','balance_alert','schedule_report_alert',
  'traffic_alert','auto_upload_rejected','daily_report','broadcast','trouble_ticket','send_soa','payment_confirmation',
  'invoice_acceptance','invoice_rejection','monitoring_alert','cleanup_summary','credential_transfer','password_reminder',
  'template_test','currency_alert','am_handover','rn_reminder','password_setup'));
