-- Real e-mail (backend step 11, go-live 2026-10-25): every e-mail is written to email_logs first and delivered by
-- the TypeScript service's e-mail job over the business company's department mailbox (SMTP), so an e-mail from any
-- part of the platform (the Elixir API's sign-in codes too) goes out the same way, is retried when the mail server is
-- down, and the log shows what really happened: queued -> sent, or failed with the server's answer.
-- Attachments (invoice PDF, rate sheet, SOA, report file) are kept with the e-mail until it is sent.

ALTER TABLE email_logs DROP CONSTRAINT IF EXISTS email_logs_status_check;
ALTER TABLE email_logs ADD CONSTRAINT email_logs_status_check CHECK (status IN ('queued', 'sent', 'failed'));
ALTER TABLE email_logs ADD COLUMN IF NOT EXISTS tries smallint NOT NULL DEFAULT 0;
ALTER TABLE email_logs ADD COLUMN IF NOT EXISTS next_try_at timestamptz;
ALTER TABLE email_logs ADD COLUMN IF NOT EXISTS sent_at timestamptz;
ALTER TABLE email_logs ADD COLUMN IF NOT EXISTS message_id text;
CREATE INDEX IF NOT EXISTS email_logs_queued_idx ON email_logs (next_try_at) WHERE status = 'queued';

CREATE TABLE IF NOT EXISTS email_attachments (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_log_id  bigint NOT NULL REFERENCES email_logs(id) ON DELETE CASCADE,
  file_name     text NOT NULL,
  content_type  text NOT NULL DEFAULT 'application/octet-stream',
  content       bytea NOT NULL
);
CREATE INDEX IF NOT EXISTS email_attachments_log_idx ON email_attachments (email_log_id);

