-- Docs tab of an enterprise: contracts, KYC files (§5.2). Bytes live in the row for the
-- fake-data phase; the Elixir backend may move them to object storage behind the same API.
CREATE TABLE enterprise_docs (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id   bigint NOT NULL REFERENCES enterprises(id),
  name            text NOT NULL,
  file_name       text NOT NULL,
  content_type    text NOT NULL DEFAULT 'application/octet-stream',
  size            integer NOT NULL,
  data            bytea NOT NULL,
  created_by_id   bigint REFERENCES users(id),
  inserted_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz,
  deleted_by_id   bigint REFERENCES users(id)
);
CREATE INDEX enterprise_docs_enterprise_idx ON enterprise_docs(enterprise_id, inserted_at DESC) WHERE deleted_at IS NULL;

