-- Re-rating requests (spec §6.3, §12.2, maker-checker) and QBR stats (§6.3), build step 5.2.
SET search_path = sms, public;

CREATE TABLE rerating_requests (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  side             text NOT NULL CHECK (side IN ('customer','vendor')),
  reprocess_type   text NOT NULL DEFAULT 'manual' CHECK (reprocess_type IN ('manual','auto')),
  description      text,
  start_date       date NOT NULL,
  end_date         date NOT NULL CHECK (end_date >= start_date),
  enterprise_ids   bigint[] NOT NULL CHECK (cardinality(enterprise_ids) > 0),
  rate_table_id    bigint NOT NULL REFERENCES rate_tables(id),
  reason           text NOT NULL DEFAULT 'rate_correction' CHECK (reason IN ('rate_correction')),
  mccmncs          text[] NOT NULL DEFAULT '{}',
  sender_id        text,
  no_note          boolean NOT NULL DEFAULT false,
  priority         text NOT NULL DEFAULT 'P2' CHECK (priority IN ('P1','P2','P3')),
  request_status   text NOT NULL DEFAULT 'pending_approval'
                   CHECK (request_status IN ('pending_approval','approved','declined')),
  reprocess_status text NOT NULL DEFAULT 'not_started'
                   CHECK (reprocess_status IN ('not_started','in_queue','in_process','completed','failed')),
  requested_by_id  bigint NOT NULL REFERENCES users(id),
  decided_by_id    bigint REFERENCES users(id),
  decided_at       timestamptz,
  decline_reason   text,
  started_at       timestamptz,
  finished_at      timestamptz,
  total_edrs       integer,
  error            text,
  updated_by_id    bigint REFERENCES users(id),
  inserted_at      timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  -- Maker-checker: the requester never decides their own request.
  CHECK (decided_by_id IS NULL OR decided_by_id <> requested_by_id)
);
CREATE INDEX rerating_requests_status_idx ON rerating_requests (request_status, reprocess_status);

-- Re-Rating Summary: one row per enterprise of a processed request.
CREATE TABLE rerating_results (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id         bigint NOT NULL REFERENCES rerating_requests(id),
  enterprise_id      bigint NOT NULL REFERENCES enterprises(id),
  total_edrs         integer NOT NULL,
  old_amount         numeric(16,6) NOT NULL,
  new_amount         numeric(16,6) NOT NULL,
  currency           char(3) NOT NULL REFERENCES currencies(iso),
  transaction_id     bigint REFERENCES transactions(id),
  transaction_status text NOT NULL CHECK (transaction_status IN ('pending','posted','not_posted','no_difference')),
  start_time         timestamptz,
  end_time           timestamptz,
  updated_by_id      bigint REFERENCES users(id),
  UNIQUE (request_id, enterprise_id)
);

-- A re-rating note is not a payment: it has no payment mode (§12.2 "type Reprocess").
ALTER TABLE transactions ALTER COLUMN payment_mode DROP NOT NULL;
ALTER TABLE transactions ADD CONSTRAINT transactions_payment_mode_required
  CHECK (payment_mode IS NOT NULL OR transaction_type = 'reprocess');

-- QBR stats per trunk and destination: traffic figures refreshed every 5 minutes from the EDR
-- store, plus a manual override per vendor stat ("Add Vendor Stat"). trunk_id is a customer or
-- vendor trunk according to side.
CREATE TABLE qbr_stats (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  side            text NOT NULL CHECK (side IN ('customer','vendor')),
  trunk_id        bigint NOT NULL,
  mccmnc_id       bigint NOT NULL REFERENCES mccmnc(id),
  attempts        integer NOT NULL DEFAULT 0,
  asr             numeric(5,1),
  dlr             numeric(5,1),
  add_s           numeric(8,1),
  overridden      boolean NOT NULL DEFAULT false,
  override_asr    numeric(5,1),
  override_dlr    numeric(5,1),
  override_add_s  numeric(8,1),
  updated_by_id   bigint REFERENCES users(id),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  refreshed_at    timestamptz,
  UNIQUE (side, trunk_id, mccmnc_id),
  CHECK (side = 'vendor' OR NOT overridden)
);
CREATE INDEX qbr_stats_mccmnc_idx ON qbr_stats (mccmnc_id, side);
