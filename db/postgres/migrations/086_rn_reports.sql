-- RN report (team trial round 7, §8, §13.10): every rate notification send, from a rate table save or a bulk rating,
-- with each e-mail's outcome (enterprise, rate table, trunks, recipients, sent or failed) as the report shown after
-- the send. Summary columns keep the list's filters and sorting on the server.
CREATE TABLE IF NOT EXISTS rn_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sent_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint REFERENCES users(id),
  source text NOT NULL CHECK (source IN ('rate_table', 'bulk_rating')),
  change_id bigint,
  note text,
  -- [{enterpriseId, enterprise, rateTable, trunks[], to[], status, reason}]
  notices jsonb NOT NULL,
  notice_count integer NOT NULL,
  sent_count integer NOT NULL,
  failed_count integer NOT NULL,
  enterprise_names text NOT NULL,
  rate_table_names text NOT NULL,
  trunk_names text NOT NULL,
  to_addresses text NOT NULL
);
CREATE INDEX IF NOT EXISTS rn_reports_sent_at ON rn_reports (sent_at DESC);
CREATE INDEX IF NOT EXISTS rn_reports_enterprises_trgm ON rn_reports USING gin (enterprise_names gin_trgm_ops);

-- The access groups that work with rates may open it.
UPDATE access_groups
   SET permissions = permissions || '{"rn-report": ["view"]}'::jsonb
 WHERE (permissions ? 'rate-manager' OR permissions ? 'incoming-rns') AND NOT permissions ? 'rn-report';
