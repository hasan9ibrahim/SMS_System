-- Security settings (spec §13.28), build step 5.21: the password policy admins can tune (never turn off),
-- and the reminders already sent, so each reminder day goes out once per password.
SET search_path = sms, public;

CREATE TABLE security_settings (
  id                     smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  password_lifetime_days integer NOT NULL DEFAULT 30 CHECK (password_lifetime_days BETWEEN 7 AND 365),
  reminder_days          integer[] NOT NULL DEFAULT '{7,3,1}',
  temp_password_hours    integer NOT NULL DEFAULT 24 CHECK (temp_password_hours BETWEEN 1 AND 72),
  min_password_length    integer NOT NULL DEFAULT 12 CHECK (min_password_length BETWEEN 12 AND 64),
  password_history       integer NOT NULL DEFAULT 12 CHECK (password_history BETWEEN 12 AND 24),
  last_reminder_run_at   timestamptz,
  updated_by_id          bigint REFERENCES users(id),
  updated_at             timestamptz NOT NULL DEFAULT now()
);
INSERT INTO security_settings (id) VALUES (1);

-- One row per reminder sent: user, the reminder day (7, 3, 1 ...) and the password it was about.
CREATE TABLE password_reminders (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_kind           text NOT NULL CHECK (user_kind IN ('staff','portal')),
  user_id             bigint NOT NULL,
  days_mark           integer NOT NULL,
  password_changed_at timestamptz NOT NULL,
  sent_at             timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_kind, user_id, days_mark, password_changed_at)
);
CREATE INDEX password_reminders_sent_idx ON password_reminders (sent_at);

ALTER TABLE email_logs DROP CONSTRAINT IF EXISTS email_logs_email_type_check;
ALTER TABLE email_logs ADD CONSTRAINT email_logs_email_type_check CHECK (email_type IN ('send_rate','send_tech_info','invoice',
  'check_smtp','bind_down_alert','otp','forgot_password','auto_upload_rate','credit_alert','balance_alert','schedule_report_alert',
  'traffic_alert','auto_upload_rejected','daily_report','broadcast','trouble_ticket','send_soa','payment_confirmation',
  'invoice_acceptance','invoice_rejection','monitoring_alert','cleanup_summary','credential_transfer','password_reminder'));

-- Security events on the overview (password changes, failures, temporary passwords, forced resets, settings).
CREATE INDEX audit_log_security_idx ON audit_log (at DESC)
  WHERE action IN ('changeMyPassword','changeMyPasswordFailed','setUserPassword','setPortalUserPassword',
                   'forcePasswordChange','updateSecuritySettings');
