-- Customer self-service portal logins (§11).
CREATE TABLE customer_portal_users (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enterprise_id            bigint NOT NULL REFERENCES enterprises(id),
  email                    text NOT NULL,
  username                 text NOT NULL,
  first_name               text NOT NULL,
  last_name                text NOT NULL,
  status                   text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  password_hash            text NOT NULL,
  password_changed_at      timestamptz NOT NULL,
  must_change_password     boolean NOT NULL DEFAULT false,
  temp_password_expires_at timestamptz,
  last_login_at            timestamptz,
  updated_by_id            bigint REFERENCES users(id),
  inserted_at              timestamptz NOT NULL DEFAULT now(),
  updated_at               timestamptz NOT NULL DEFAULT now(),
  deleted_at               timestamptz
);
CREATE UNIQUE INDEX customer_portal_users_username_uq ON customer_portal_users (lower(username)) WHERE deleted_at IS NULL;
CREATE INDEX customer_portal_users_enterprise_idx ON customer_portal_users (enterprise_id);

-- The last passwords of a staff or portal user, as hashes only (§13.28: not one of the last 12).
CREATE TABLE password_history (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         bigint REFERENCES users(id),
  portal_user_id  bigint REFERENCES customer_portal_users(id),
  password_hash   text NOT NULL,
  changed_at      timestamptz NOT NULL,
  CHECK ((user_id IS NULL) <> (portal_user_id IS NULL))
);
CREATE INDEX password_history_user_idx ON password_history (user_id, changed_at DESC);
CREATE INDEX password_history_portal_idx ON password_history (portal_user_id, changed_at DESC);

-- Logged In Users (§11): open and ended sessions of staff and portal users.
CREATE TABLE user_sessions (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_kind       text NOT NULL CHECK (user_kind IN ('staff','customer')),
  user_id         bigint REFERENCES users(id),
  portal_user_id  bigint REFERENCES customer_portal_users(id),
  ip              inet NOT NULL,
  location        text,
  device          text NOT NULL CHECK (device IN ('desktop','mobile','tablet','bot')),
  os              text NOT NULL,
  browser         text NOT NULL,
  logged_in_at    timestamptz NOT NULL,
  last_seen_at    timestamptz NOT NULL,
  ended_at        timestamptz,
  ended_by_id     bigint REFERENCES users(id),
  end_reason      text CHECK (end_reason IN ('logout','forced','expired','password_change')),
  CHECK ((user_kind = 'staff') = (user_id IS NOT NULL)),
  CHECK ((user_kind = 'customer') = (portal_user_id IS NOT NULL))
);
CREATE INDEX user_sessions_open_idx ON user_sessions (logged_in_at DESC) WHERE ended_at IS NULL;
CREATE INDEX user_sessions_user_idx ON user_sessions (user_id) WHERE ended_at IS NULL;

-- Audit Trail (§11): every call that changes something.
CREATE TABLE audit_log (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at           timestamptz NOT NULL DEFAULT now(),
  user_id      bigint REFERENCES users(id),
  ip           inet,
  module       text NOT NULL,
  controller   text NOT NULL,
  method       text NOT NULL,
  action       text NOT NULL,
  table_name   text,
  master_id    text,
  status       smallint NOT NULL,
  duration_ms  integer NOT NULL DEFAULT 0
);
CREATE INDEX audit_log_at_idx ON audit_log (at DESC);
CREATE INDEX audit_log_user_idx ON audit_log (user_id, at DESC);

