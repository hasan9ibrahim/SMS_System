-- One sender block per department mailbox. Secrets are stored encrypted and never returned.
CREATE TABLE business_company_mailboxes (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_company_id  bigint NOT NULL REFERENCES business_companies(id),
  department           text NOT NULL CHECK (department IN ('noc','sales','rates','billing','support')),
  name                 text,
  phone                text,
  smtp_email           text NOT NULL,
  smtp_secure          text NOT NULL DEFAULT 'starttls' CHECK (smtp_secure IN ('none','ssl','starttls')),
  smtp_host            text NOT NULL,
  smtp_port            integer NOT NULL DEFAULT 587,
  smtp_username        text,
  smtp_password_enc    text,
  extension            text,
  skype_name           text,
  oauth_redirect_uris  text[] NOT NULL DEFAULT '{}',
  client_id            text NOT NULL,
  client_secret_enc    text,
  last_check_at        timestamptz,
  last_check_ok        boolean,
  UNIQUE (business_company_id, department)
);

-- Company Logo (PNG) and the Invoice / Customer Rate / SOA format files (XLSX).
CREATE TABLE business_company_files (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_company_id  bigint NOT NULL REFERENCES business_companies(id),
  kind                 text NOT NULL CHECK (kind IN ('logo','invoice_format','customer_rate_format','soa_format')),
  name                 text NOT NULL,
  content_type         text NOT NULL,
  size                 integer NOT NULL,
  content              bytea NOT NULL,
  uploaded_by_id       bigint REFERENCES users(id),
  uploaded_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (business_company_id, kind)
);

