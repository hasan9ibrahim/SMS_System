-- Margin calculator (team trial round 3): saved swap deals, SMS version of the team's sheet. Two legs as JSON
-- (outbound = we send to the carrier, inbound = the carrier sends to us); totals are worked out on save.
SET search_path = sms, public;

CREATE TABLE IF NOT EXISTS margin_deals (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                  text NOT NULL,
  carrier_enterprise_id bigint REFERENCES enterprises(id),
  carrier_name          text NOT NULL,
  currency              char(3) NOT NULL DEFAULT 'EUR',
  period_days           integer NOT NULL DEFAULT 30 CHECK (period_days BETWEEN 1 AND 366),
  notes                 text,
  outbound              jsonb NOT NULL DEFAULT '[]',
  inbound               jsonb NOT NULL DEFAULT '[]',
  total_margin          numeric(20, 6) NOT NULL DEFAULT 0,
  netting               numeric(20, 6) NOT NULL DEFAULT 0,
  created_by_id         bigint NOT NULL REFERENCES users(id),
  updated_by_id         bigint NOT NULL REFERENCES users(id),
  inserted_at           timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS margin_deals_updated_idx ON margin_deals (updated_at DESC);
